"""Record real qloo CLI behavior into docs/QLOO_NOTES.md.

Usage (from backend/):  python scripts/discover_qloo.py

- Always runs: version, help texts, and --dry-run requests (no Qloo call is made).
  The CLI insists on *some* key even for --dry-run, so a placeholder is supplied
  for dry runs when QLOO_API_KEY is unset.
- Runs live searches only when QLOO_API_KEY is set in the environment.
"""

import json
import os
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NOTES = ROOT / "docs" / "QLOO_NOTES.md"
QLOO = os.getenv("QLOO_BIN", "qloo")
MAX_OUT = 1800

DEMO_SEARCHES = [
    ("Coke Studio", "artist"),
    ("chai", "place"),
    ("street food", "place"),
    ("Toronto", "locality"),
]


def run(args: list[str], env: dict | None = None) -> tuple[int, str]:
    try:
        p = subprocess.run([QLOO, *args], capture_output=True, text=True, timeout=30, env=env)
    except FileNotFoundError:
        return 127, "qloo CLI not found. Install: npm install -g @qloo/qloo-harness@0.1.26 (Node >= 22.19.0)"
    except subprocess.TimeoutExpired:
        return 124, "timed out after 30 s"
    out = (p.stdout + ("\n[stderr]\n" + p.stderr if p.stderr.strip() else "")).strip()
    key = os.getenv("QLOO_API_KEY", "")
    if key:
        out = out.replace(key, "[redacted]")
    return p.returncode, out[:MAX_OUT] + ("\n... (truncated)" if len(out) > MAX_OUT else "")


def block(cmd: list[str], rc: int, out: str) -> str:
    return f"```text\n$ qloo {' '.join(cmd)}\n(exit {rc})\n{out}\n```\n"


def main() -> int:
    has_key = bool(os.getenv("QLOO_API_KEY"))
    dry_env = dict(os.environ)
    if not has_key:
        dry_env["QLOO_API_KEY"] = "dry-run-placeholder"

    sections = []
    for cmd in (["--version"], ["api", "--help"], ["exec", "--help"], ["api", "search", "--help"], ["api", "insights", "--help"]):
        rc, out = run(cmd)
        sections.append(block(cmd, rc, out))
        if cmd == ["--version"] and rc != 0:
            print("qloo CLI not available:", out)

    dry = []
    for query, typ in DEMO_SEARCHES:
        cmd = ["api", "search", f"--query={query}", f"--type={typ}", "--take=3", "--json", "--dry-run"]
        dry.append(block(cmd, *run(cmd, dry_env)))
    cmd = ["api", "insights", "--type=place", "--signal-entities=ENTITY_ID_1,ENTITY_ID_2",
           "--filter-location=Toronto", "--take=10", "--json", "--dry-run"]
    dry.append(block(cmd, *run(cmd, dry_env)))

    live = []
    if has_key:
        for query, typ in DEMO_SEARCHES:
            cmd = ["api", "search", f"--query={query}", f"--type={typ}", "--take=3", "--json"]
            live.append(block(cmd, *run(cmd)))
    else:
        live.append("_Not run: QLOO_API_KEY is not set. Live output shapes are unverified._\n")

    NOTES.parent.mkdir(exist_ok=True)
    NOTES.write_text(
        HEADER.format(today=date.today().isoformat(), live="yes" if has_key else "no")
        + "\n## Raw: version and help\n\n" + "\n".join(sections)
        + "\n## Raw: dry-run requests (no Qloo call made)\n\n" + "\n".join(dry)
        + "\n## Raw: live searches\n\n" + "\n".join(live)
    )
    print(f"wrote {NOTES} (live calls: {'yes' if has_key else 'no'})")
    return 0


HEADER = """# Qloo notes

Generated by `backend/scripts/discover_qloo.py` on {today}. Live calls in this run: **{live}**.
Re-run the script after setting `QLOO_API_KEY` to record real response shapes.

## What discovery confirmed (CLI @qloo/qloo-harness 0.1.26)

| Capability | Command used by the adapter | HTTP request (from `--dry-run`) |
|---|---|---|
| Entity search | `qloo api search --query=<text> --type=<alias> --take=<n> --json` | `GET https://api.qloo.com/search` with `query`, `types`, `take` |
| Recommendations seeded by entities | `qloo api insights --type=<alias> --signal-entities=<id,id> --take=<n> --json` | `GET https://api.qloo.com/v2/insights` with `filter.type`, `signal.interests.entities` |
| Location filtering for a city | `--filter-location=Toronto` on `insights` | adds `filter.location.query=Toronto` |

Type aliases accepted by `--type` (from `qloo api search --help`): `artist`, `place` (= restaurant),
`tv_show`, `movie`, `book`, `brand`, `podcast`, `locality`, and more.

`qloo exec` workflows also exist (`recommend, rank, describe, where_popular, compare_audiences,
entity_tags, audience_demographics, trends, find_tags`). The adapter does **not** use them; the two
`api` commands above cover everything TasteBridge needs and their request shapes are visible via `--dry-run`.

## Corrections to the build prompt

- `--api-key` exists on the CLI (and warns when used). The adapter never passes it; the CLI reads
  `QLOO_API_KEY` from the environment.
- Node.js on this machine was 20.x; the CLI requires >= 22.19.0 (installed 22.23 via nvm).
- `--dry-run` still requires *a* key to be present (it exits 3 otherwise), even though it makes no request.
- Credential setup that was observed: `QLOO_API_KEY` env var, or `qloo api config set api-key <key>`.
  `qloo setup --qloo` from the prompt was not verified.

## Output and errors (read from the CLI source `dist/router.js`, confirmed where noted)

- `--json` prints the entity array directly: `JSON.stringify(response.results.entities)` for insights
  and `JSON.stringify(response.results)` for search. Entity fields used by the CLI's own table view:
  `entity_id`, `name`, `type`, `subtype`, `affinity` (or `query.affinity`), `popularity`,
  `properties.address`, `tags[].name`. **Not yet observed live.**
- Errors are printed as JSON on stdout: `{{"error":true,"code":"...","message":"..."}}`.
- Exit codes: 0 ok, 2 bad usage, 3 auth (`AUTH_FAILED`, observed with no key), 4 not found,
  5 API error (`API_ERROR`; a bad key was observed as `"API request failed: 401 Unauthorized"`).
  HTTP 429 arrives as exit 5 with the server's message; the adapter matches `429` / `rate limit` text.
- Adapter mapping: exit 3 or 401/403 text -> `QlooAuthError`; 429 text -> `QlooRateLimitError`;
  exit 4 -> `QlooNoResult`; anything else, timeouts and non-JSON output -> `QlooUnavailable`.
- `affinity` is shown on cards exactly as returned. If it is absent, the card shows Qloo's rank
  position instead and says so.

## Not found / degraded

- Qloo returns cultural affinities, not prices, travel times, diet info or event dates. Those fields stay
  `null` ("not verified") for Qloo cards. Practical logistics come only from `data/curated_toronto.json`.
"""

if __name__ == "__main__":
    sys.exit(main())
